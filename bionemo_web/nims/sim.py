def _sim_dock(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    protein_input = payload.get("protein") or ""
    ligand = payload.get("ligand") or payload.get("smiles") or ""
    num_poses = int(payload.get("num_poses") or 10)
    warnings: List[str] = []

    if not ligand.strip():
        return {"raw": {"error": "No ligand supplied."}, "canonical": {}, "meta": {},
                "warnings": ["Provide a ligand as SMILES or SDF."], "method": SIM_METHODS["dock"]}

    structure, fold_meta = _protein_from_input(protein_input, seed, warnings)
    if structure is None:
        return {"raw": {"error": "No usable protein supplied."}, "canonical": {}, "meta": {},
                "warnings": warnings or ["Provide a protein as PDB or sequence."],
                "method": SIM_METHODS["dock"]}

    pockets = structure.find_pockets(top=4)
    result = dock_mod.dock(
        structure, ligand, num_poses=max(1, min(num_poses, 40)), seed=seed, pockets=pockets
    )
    poses = result.get("poses", [])
    if result.get("error"):
        warnings.append(result["error"])
    payload_out = dock_mod.poses_to_nim_format(poses, result.get("ligand_atom_count", 0))
    raw = {**payload_out, "_simulated": True, "_method": SIM_METHODS["dock"]}
    canonical = {
        "ligand_positions": payload_out["ligand_positions"],
        "position_confidence": payload_out["position_confidence"],
        "ligand": ligand,
    }
    meta = {
        "poses": poses,
        "pose_stats": [p.to_dict() for p in poses],
        "pockets": pockets,
        "structure": structure,
        "n_pockets": len(pockets),
        "pose_diversity_mean_rmsd": result.get("pose_diversity_mean_rmsd"),
        "ligand_radius": result.get("ligand_radius"),
        "ligand_atom_count": result.get("ligand_atom_count", 0),
        "fold_meta": fold_meta,
        "top_pose_hbonds": poses[0].hbonds if poses else 0,
    }
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["dock"]}


# --------------------------------------------------------------------------
# Sequence design (inverse folding)
# --------------------------------------------------------------------------


def _design_from_structure(
    structure: "st_mod.Structure",
    *,
    num_sequences: int = 8,
    temperature: float = 0.1,
    fixed_positions: Optional[Sequence[int]] = None,
    seed: int = 11,
) -> List[Dict[str, Any]]:
    """Sample sequences compatible with a backbone.

    The position-wise preference is built from real geometry -- relative solvent
    accessibility (Shrake-Rupley), CA contact count and local flexibility -- and
    combined with a wild-type prior that is strong in the buried core and weak at
    the surface.  Sampling then follows a softmax at ``temperature``, which is
    how ProteinMPNN's sampling temperature behaves too: low = conservative.
    """
    seq = structure.sequence()
    n = len(seq)
    if n == 0:
        return []
    rel_sasa = structure.relative_sasa()
    contacts = structure.residue_contacts()
    ss = structure.secondary_structure()
    fixed = {int(p) - 1 for p in (fixed_positions or []) if str(p).strip().isdigit()}
    rng = np.random.default_rng(seed)

    letters = "ACDEFGHIKLMNPQRSTVWY"
    kd = np.array([CHEM[a] for a in letters])
    vol = np.array([SIZE[a] for a in letters])
    flex = np.array([FLEX[a] for a in letters])
    charge = np.array([CHARGE[a] for a in letters])
    helix = np.array([1.0 if a in "EMALK" else 0.0 for a in letters])
    sheet = np.array([1.0 if a in "VIYFWLT" else 0.0 for a in letters])

    logits = np.zeros((n, len(letters)))
    for i in range(n):
        burial = float(np.clip(1.0 - min(1.0, rel_sasa[i] if i < len(rel_sasa) else 0.5), 0.0, 1.0))
        n_contacts = float(contacts[i]) if i < len(contacts) else 5.0
        packed = float(np.clip(n_contacts / 14.0, 0.0, 1.0))
        row = -0.35 * (vol - vol.mean()) / vol.std() * (0.5 + 0.5 * packed)
        row += 0.9 * burial * (kd - kd.mean()) / kd.std()
        row -= 0.55 * (1.0 - burial) * (kd - kd.mean()) / kd.std()
        row -= 0.8 * burial * np.abs(charge)
        row += 0.25 * (1.0 - burial) * np.abs(charge)
        if i < len(ss) and ss[i] in "HG":
            row += 0.7 * helix
            row -= 0.6 * np.array([1.0 if a == "P" else 0.0 for a in letters])
        elif i < len(ss) and ss[i] == "E":
            row += 0.55 * sheet
        row += 0.28 * (1.0 - packed) * (flex - flex.mean()) / flex.std()
        # wild-type prior: strong in the core, permissive at the surface
        wt = letters.find(seq[i])
        if wt >= 0:
            row[wt] += 0.35 + 1.15 * burial
        logits[i] = row

    temperature = max(0.02, float(temperature))
    results: List[Dict[str, Any]] = []
    for s in range(max(1, num_sequences)):
        out_letters: List[str] = []
        logp: List[float] = []
        for i in range(n):
            if i in fixed:
                out_letters.append(seq[i])
                logp.append(0.0)
                continue
            z = logits[i] / temperature
            z -= z.max()
            p = np.exp(z)
            p /= p.sum()
            pick = int(rng.choice(len(letters), p=p))
            out_letters.append(letters[pick])
            logp.append(float(np.log(max(p[pick], 1e-12))))
        designed = "".join(out_letters)
        recovery = sum(a == b for a, b in zip(designed, seq)) / n
        results.append(
            {
                "sequence": designed,
                "score": round(float(np.mean(logp)), 4),
                "global_score": round(float(np.sum(logp)), 2),
                "recovery": round(recovery, 4),
                "local_scores": [round(v, 3) for v in logp],
                "temperature": temperature,
                "n_fixed": len(fixed),
            }
        )
    results.sort(key=lambda r: -r["score"])
    for rank, row in enumerate(results, start=1):
        row["rank"] = rank
        row["report"] = seq_mod.analyse_protein(row["sequence"]).to_dict()
        row["mutations"] = [
            {"position": i + 1, "wild_type": seq[i], "designed": row["sequence"][i]}
            for i in range(n)
            if row["sequence"][i] != seq[i]
        ]
    return results


