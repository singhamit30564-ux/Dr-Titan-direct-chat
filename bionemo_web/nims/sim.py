def _protein_from_input(
    protein_input: str, seed: int, warnings: List[str]
) -> Tuple[Optional["st_mod.Structure"], Dict[str, Any]]:
    """Accept PDB text, a FASTA/sequence, or a bare structure and return a Structure."""
    text = (protein_input or "").strip()
    if not text:
        return None, {}
    if "ATOM" in text[:4000] or "HETATM" in text[:4000]:
        structure = st_mod.parse_pdb(text)
        if structure.n_residues == 0:
            warnings.append("The PDB text contained no amino-acid residues.")
            return None, {}
        return structure, {}
    seq, w = seq_mod.clean_sequence(text)
    warnings.extend(w)
    if not seq:
        return None, {}
    if seq_mod.detect_sequence_type(seq) != "protein":
        warnings.append("Input did not look like a protein sequence.")
    if len(seq) > 500:
        warnings.append(f"Sequence truncated to 500 residues for the simulation backend "
                        f"(input {len(seq)}); fold the PDB with a real NIM for large targets.")
        seq = seq[:500]
    structure = st_mod.fold_sequence(seq, seed=seed, label="simulated-receptor")
    warnings.append(
        "Receptor was folded by the console's simulation model (no experimental structure supplied)."
    )
    return structure, structure.meta
