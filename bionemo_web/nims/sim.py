"""Deterministic simulation backends.

When no local NIM container is running and no NVIDIA API key is configured the
console can still answer -- using the analysis engines in
:mod:`bionemo_web.bio` and :mod:`bionemo_web.nims.docking`.  Two rules make this
honest rather than hand-waving:

1. **Every response carries the NIM's own JSON shape.**  The simulator returns,
   for example, ``{"molecules": [{"smiles": ..., "score": ...}]}`` or
   ``{"ligand_positions": [[...]], "position_confidence": [...]}`` so the exact
   same normaliser, UI code path and export logic runs for simulated and real
   calls.  There is no "fake mode" branch inside the app.
2. **The numbers are computed, not invented.**  Molecules are real RDKit
   validated structures with real QED/SA/logP values; structures are built in
   torsional space with ideal Engh-Huber geometry; poses are real 3D coordinates
   scored by a documented physical objective; DNA is generated by a Markov chain
   whose reported probabilities are the model's actual probabilities.

Every simulated run is tagged ``backend="simulated"`` and the UI shows a badge
with the method description, so a simulated result can never be mistaken for a
NIM prediction.
"""

from __future__ import annotations

import math
from collections import Counter
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np

from ..bio import chem as chem_mod
from ..bio import embed as embed_mod
from ..bio import sequence as seq_mod
from ..bio import structure as st_mod
from . import docking as dock_mod
from .catalog import NimSpec

SIM_METHODS = {
    "fold": "torsional Monte Carlo folding (ideal Geometry + HP potential, Flory Rg restraint)",
    "embeddings": "physicochemical feature projection (deterministic random projection of property matrix)",
    "molecules": "BRICS recombination + R-group enumeration + bioisosteric replacement, RDKit validated",
    "dock": "ETKDGv3 conformers + rigid-body hill climbing on clash/contact/H-bond/burial score",
    "design": "burial-conditioned position-wise residue sampling (inverse folding heuristic)",
    "genomics": "6-mer Markov chain over the prompt with codon-flavour smoothing",
}


# --------------------------------------------------------------------------
# Dispatcher
# --------------------------------------------------------------------------


def simulate(spec: NimSpec, payload: Dict[str, Any], *, seed: int = 20241011) -> Dict[str, Any]:
    """Run the simulator for ``spec`` and return a NIM-shaped response bundle.

    Returns ``{"raw", "canonical", "meta", "warnings", "method"}``.

    Every bundle that leaves this function carries an explicit warning and
    ``meta["simulated"] = True``. That is deliberate: the console is allowed to
    fall back to its own models, but it is never allowed to do so quietly.
    """
    kind = spec.kind
    try:
        if kind == "fold":
            bundle = _sim_fold(spec, payload, seed)
        elif kind == "embeddings":
            bundle = _sim_embeddings(spec, payload, seed)
        elif kind == "molecules":
            bundle = _sim_molecules(spec, payload, seed)
        elif kind == "dock":
            bundle = _sim_dock(spec, payload, seed)
        elif kind == "design":
            bundle = _sim_design(spec, payload, seed)
        elif kind == "genomics":
            bundle = _sim_genomics(spec, payload, seed)
        else:
            return {
                "raw": {"error": "simulation not implemented for this task"},
                "canonical": {},
                "meta": {"simulated": True},
                "warnings": [f"No simulator exists for task '{spec.task}'."],
                "method": "not implemented",
            }
    except Exception as exc:  # surfaced to the UI instead of crashing the app
        return {
            "raw": {"error": str(exc)},
            "canonical": {},
            "meta": {"simulated": True},
            "warnings": [f"Simulation failed: {exc}"],
            "method": SIM_METHODS.get(kind, "n/a"),
        }

    warnings = list(bundle.get("warnings") or [])
    if not any("SIMULATED" in str(w).upper() for w in warnings):
        warnings.insert(
            0,
            "SIMULATED RESULT: produced by the console's built-in "
            f"{bundle.get('method') or SIM_METHODS.get(kind, 'model')}. It is a documented "
            "physical/statistical model, not a prediction from a trained NVIDIA NIM.",
        )
    bundle["warnings"] = warnings
    meta = dict(bundle.get("meta") or {})
    meta["simulated"] = True
    bundle["meta"] = meta
    return bundle


# --------------------------------------------------------------------------
# Structure prediction / generation
# --------------------------------------------------------------------------


def _sim_fold(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    sequence = payload.get("sequence") or payload.get("fasta") or ""
    pdb_input = payload.get("pdb") or ""
    warnings: List[str] = []
    meta: Dict[str, Any] = {}

    if pdb_input.strip().startswith(("HEADER", "ATOM", "HETATM")) or "ATOM" in pdb_input[:400]:
        structure = st_mod.parse_pdb(pdb_input)
        warnings.append("Input was already a structure; it is echoed back rather than re-predicted.")
    else:
        seq, seq_warnings = seq_mod.clean_sequence(sequence)
        warnings.extend(seq_warnings)
        if not seq:
            return {
                "raw": {"error": "No sequence supplied."},
                "canonical": {},
                "meta": {},
                "warnings": ["Provide an amino-acid sequence."],
                "method": SIM_METHODS["fold"],
            }
        if len(seq) > 700:
            warnings.append(
                f"Sequence truncated to 700 residues for the simulation backend (input {len(seq)})."
            )
            seq = seq[:700]
        structure = st_mod.fold_sequence(seq, seed=seed, label="simulated")
        meta["fold_meta"] = structure.meta

    plddt = structure.plddt()
    canonical = {
        "pdbs": [structure.pdb_text],
        "plddt": [float(v) for v in plddt] if plddt is not None else None,
        "mean_plddt": float(plddt.mean()) if plddt is not None and len(plddt) else None,
        "ptm": round(float(np.clip(0.35 + 0.006 * (plddt.mean() if plddt is not None else 50), 0, 0.95)), 3),
        "pae": None,
        "affinity": None,
    }
    raw = {
        "pdbs": [structure.pdb_text],
        "plddt": canonical["plddt"],
        "ptm": canonical["ptm"],
        "mean_plddt": canonical["mean_plddt"],
        "_simulated": True,
        "_method": SIM_METHODS["fold"],
    }
    meta.update(
        {
            "structure": structure,
            "radius_of_gyration": structure.radius_of_gyration(),
            "predicted_ss": structure.meta.get("predicted_ss", ""),
            "sequence": structure.sequence(),
            "disclaimer": structure.meta.get("disclaimer", ""),
        }
    )
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["fold"]}


