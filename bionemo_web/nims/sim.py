# Molecule generation
# --------------------------------------------------------------------------


def _sim_molecules(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    is_genmol = spec.key == "genmol"
    seed_smiles = (
        (payload.get("smi") or payload.get("smiles") or "") if is_genmol
        else (payload.get("smi") or payload.get("smiles") or "")
    )
    n = int(payload.get("num_molecules") or 10)
    n = max(1, min(n, 200))
    min_sim = float(payload.get("min_similarity") or (0.0 if is_genmol else 0.3))
    property_name = str(payload.get("property_name") or payload.get("scoring") or "QED")
    minimize = bool(payload.get("minimize") or False)
    # GenMol's masked SMILES uses [*{n-m}] placeholders; strip them for the seed.
    if is_genmol and "[*" in seed_smiles:
        # GenMol marks positions to fill with [*{n-m}] placeholders. Drop only
        # those tokens (never ring-closure digits or stereochemistry).
        import re as _re

        cleaned_seed = _re.sub(r"\[\*[^\]]*\]", "", seed_smiles).strip(" .")
    else:
        cleaned_seed = seed_smiles

    if not cleaned_seed.strip():
        return {"raw": {"error": "No seed SMILES supplied."}, "canonical": {}, "meta": {},
                "warnings": ["Provide a seed SMILES."], "method": SIM_METHODS["molecules"]}

    temperature = float(payload.get("temperature") or 1.0)
    rows = chem_mod.generate_analogues(
        cleaned_seed,
        n=n,
        min_similarity=min_sim,
        max_similarity=1.0,
        seed=seed,
        property_name=property_name,
        minimize=minimize,
        scaffold_hop=is_genmol and temperature >= 1.5,
    )
    if not rows:
        return {"raw": {"error": "The seed could not be parsed."}, "canonical": {}, "meta": {},
                "warnings": [f"RDKit could not parse the seed SMILES: {cleaned_seed[:60]}"],
                "method": SIM_METHODS["molecules"]}

    # NIM shape: {"molecules": [{"smiles": ..., "score": ...}]} / GenMol adds status.
    raw = {
        "status": "success",
        "molecules": [{"smiles": r["smiles"], "score": r["score"]} for r in rows],
        "generated": [{"sample": r["smiles"], "score": r["score"]} for r in rows],
        "_simulated": True,
    }
    canonical = {
        "molecules": [{"smiles": r["smiles"], "score": r["score"], "extra": {}} for r in rows],
        "status": "success",
    }
    seed_report = chem_mod.report_molecule(cleaned_seed)
    meta = {
        "rows": rows,
        "seed_smiles": cleaned_seed,
        "seed_report": seed_report.to_dict(),
        "property_name": property_name,
        "minimize": minimize,
        "set_summary": chem_mod.summarise_set([r["smiles"] for r in rows]),
        "sim_similarities": [r["similarity"] for r in rows],
        "is_genmol": is_genmol,
    }
    warnings = list(seed_report.warnings)
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["molecules"]}


