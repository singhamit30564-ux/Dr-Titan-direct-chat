class KmerMarkovModel:
    """A transparent k-mer Markov chain over DNA, fitted on the prompt itself.

    Generation reports the *model's own* per-token probabilities, so the numbers
    in the UI are the probabilities of the actual generative process rather than
    a plausible-looking curve.
    """

    def __init__(self, k: int = 6, smoothing: float = 0.35) -> None:
        self.k = k
        self.smoothing = smoothing
        self.counts: Dict[str, Counter] = {}
        self.totals: Counter = Counter()

    def fit(self, sequence: str) -> "KmerMarkovModel":
        s = (sequence or "").upper().replace("U", "T")
        self.totals = Counter(s)
        for i in range(len(s) - self.k):
            ctx = s[i : i + self.k]
            nxt = s[i + self.k]
            self.counts.setdefault(ctx, Counter())[nxt] += 1
        return self

    def probs(self, context: str) -> Dict[str, float]:
        key = context[-self.k :].upper()
        obs = self.counts.get(key, Counter())
        total = sum(obs.values()) + 4 * self.smoothing
        backoff_total = sum(self.totals.values()) or 1
        return {
            base: (obs.get(base, 0.0) + self.smoothing * (self.totals.get(base, 0) / backoff_total)
                   + 1e-9) / max(total, 1e-9)
            for base in "ACGT"
        }

    def generate(
        self, prompt: str, n_tokens: int, temperature: float = 0.7, seed: int = 3,
        top_k: int = 0,
    ) -> Tuple[str, List[float], List[Dict[str, float]]]:
        rng = np.random.default_rng(seed)
        seq = prompt.upper().replace("U", "T")
        if not seq:
            seq = "ATG"
        generated = []
        probs_out: List[float] = []
        steps: List[Dict[str, float]] = []
        for _ in range(max(0, n_tokens)):
            p = self.probs(seq)
            bases = list(p.keys())
            values = np.array([p[b] for b in bases], dtype=float)
            if temperature > 0:
                values = np.power(values, 1.0 / max(temperature, 1e-3))
            values /= values.sum()
            if top_k and top_k < len(bases):
                order = np.argsort(-values)
                mask = np.zeros_like(values, dtype=bool)
                mask[order[:top_k]] = True
                values = np.where(mask, values, 0.0)
                values /= values.sum()
            pick = int(rng.choice(len(bases), p=values))
            base = bases[pick]
            generated.append(base)
            probs_out.append(float(values[pick]))
            steps.append({b: round(float(v), 5) for b, v in zip(bases, values)})
            seq += base
        return "".join(generated), probs_out, steps


def _sim_genomics(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    prompt = payload.get("sequence") or payload.get("dna") or ""
    seq, warnings = seq_mod.clean_sequence(prompt)
    n_tokens = int(payload.get("num_tokens") or 100)
    temperature = float(payload.get("temperature") or 0.7)
    top_k = int(payload.get("top_k") or 0)
    if not seq:
        # Evo 2 can start from nothing; seed with a standard start codon context.
        seq = "ATG"
        warnings.append("No prompt supplied; generation started from 'ATG'.")

    model = KmerMarkovModel(k=6).fit(seq)
    generated, probs, steps = model.generate(seq, n_tokens, temperature=temperature, seed=seed, top_k=top_k)
    full = seq + generated
    analysis = seq_mod.analyse_dna(full)
    canonical = {
        "sequence": full,
        # 'generated' is the newly synthesised suffix only; 'sequence' is the whole
        # product. Both are exposed because different NIM versions return one or
        # the other, and the UI should never have to guess.
        "generated": generated,
        "probs": probs if payload.get("enable_sampled_probs", True) else None,
        "scores": {
            "mean_log_prob": round(float(np.mean(np.log(np.clip(probs, 1e-9, 1.0)))), 4) if probs else None,
            "mean_token_probability": round(float(np.mean(probs)), 4) if probs else None,
        },
    }
    raw = {
        "sequence": full,
        "generated_sequence": generated,
        "probs": probs,
        "_simulated": True,
        "gc_content": analysis["gc_content"],
    }
    meta = {
        "prompt": seq,
        "generated": generated,
        "analysis": analysis,
        "token_steps": steps[:200],
        "kmer_counts": len(model.counts),
        "orf_count": analysis["orf_count"],
        "longest_orf_aa": analysis["longest_orf_aa"],
    }
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["genomics"]}


