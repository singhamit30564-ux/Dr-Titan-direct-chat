# Embeddings
# --------------------------------------------------------------------------


def _sim_embeddings(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    sequence = payload.get("sequence") or ""
    seq, warnings = seq_mod.clean_sequence(sequence)
    if not seq:
        return {"raw": {"error": "No sequence supplied."}, "canonical": {}, "meta": {},
                "warnings": ["Provide an amino-acid sequence."], "method": SIM_METHODS["embeddings"]}
    embeddings = embed_mod.simulated_embeddings(seq, dim=128, seed=seed)
    mean = np.asarray(embeddings, dtype=float).mean(0).round(5).tolist() if embeddings else []
    canonical = {"embeddings": embeddings, "mean": mean}
    raw = {"embeddings": embeddings, "mean_embeddings": mean, "_simulated": True}
    meta = {
        "sequence": seq,
        "quality": embed_mod.embedding_quality_report(seq, embeddings),
        "projection": embed_mod.project_embeddings(embeddings),
        "clusters": embed_mod.cluster_embeddings(embeddings, n_clusters=min(8, max(2, len(seq) // 15))),
        "feature_names": embed_mod.FEATURE_NAMES,
    }
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["embeddings"]}


