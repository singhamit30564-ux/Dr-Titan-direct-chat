def _sim_design(spec: NimSpec, payload: Dict[str, Any], seed: int) -> Dict[str, Any]:
    pdb = payload.get("pdb") or ""
    warnings: List[str] = []
    if "ATOM" in pdb or "HETATM" in pdb:
        structure = st_mod.parse_pdb(pdb)
    else:
        sequence = payload.get("sequence") or ""
        seq, w = seq_mod.clean_sequence(sequence)
        warnings.extend(w)
        if not seq:
            return {"raw": {"error": "No backbone or sequence supplied."}, "canonical": {}, "meta": {},
                    "warnings": ["Provide a backbone PDB (preferred) or a sequence."],
                    "method": SIM_METHODS["design"]}
        structure = st_mod.fold_sequence(seq, seed=seed, label="simulated-backbone")
        warnings.append(
            "No backbone was supplied, so a simulated backbone was folded from the sequence first."
        )

    fixed = []
    for token in str(payload.get("fixed_positions") or "").replace(";", ",").split(","):
        token = token.strip()
        if token.isdigit():
            fixed.append(int(token))
    num_sequences = int(payload.get("num_sequences") or 8)
    temperature = float(payload.get("sampling_temp") or 0.1)
    designs = _design_from_structure(
        structure,
        num_sequences=max(1, min(num_sequences, 100)),
        temperature=temperature,
        fixed_positions=fixed,
        seed=seed,
    )
    raw = {
        "sequences": [{"sequence": d["sequence"], "score": d["score"],
                       "global_score": d["global_score"], "recovery": d["recovery"]} for d in designs],
        "_simulated": True,
    }
    canonical = {"sequences": raw["sequences"], "pdb": structure.pdb_text}
    meta = {
        "designs": designs,
        "structure": structure,
        "input_sequence": structure.sequence(),
        "fixed_positions": fixed,
        "temperature": temperature,
        "relative_sasa": [round(float(v), 3) for v in structure.relative_sasa()],
        "secondary_structure": structure.secondary_structure(),
    }
    return {"raw": raw, "canonical": canonical, "meta": meta, "warnings": warnings,
            "method": SIM_METHODS["design"]}


